-- Custo real (AC do Valor Ganho).
--
-- Ate aqui o AC era deduzido do orcamento: `quantidade executada x preco
-- unitario`. Como o EV tambem e `peso x progresso real` (e peso e
-- `quantidade planejada x preco unitario`, e progresso real e
-- `executado / planejado`), os dois lados davam exatamente o mesmo numero e o
-- CPI ficava travado em 1,000 para sempre. Este erro nao aparecia como erro:
-- aparecia como "obra sempre no orcamento".
--
-- Esta tabela guarda o dinheiro que saiu, com data de competencia (fato
-- gerador), para o `asOf` poder cortar por data.
